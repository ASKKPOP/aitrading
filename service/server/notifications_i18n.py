def _pick(fam: dict[str, dict[str, str]], lang: str, key: str) -> str:
    return fam.get(lang, {}).get(key) or fam['en'].get(key, key)


def verdict_default(side: str, lang: str = 'en') -> str:
    """The deterministic verdict, used when the LLM layer is off or fails."""
    code = normalize_lang(lang)
    tmpl = _VERDICT.get(code, _VERDICT['en'])[1]
    return tmpl.format(side=_pick(_SIDE, code, side))


def verdict_sentence(stance: str, side: str, urgency: str, note: str,
                     lang: str = 'en') -> str:
    """The LLM-enriched verdict. `note` arrives already in `lang`; everything
    else is a closed enum rendered from the tables above."""
    code = normalize_lang(lang)
    tmpl = _VERDICT.get(code, _VERDICT['en'])[0]
    try:
        return tmpl.format(stance=_pick(_STANCE, code, stance),
                           side=_pick(_SIDE, code, side),
                           urgency=_pick(_URGENCY, code, urgency),
                           note=note)
    except (KeyError, IndexError, ValueError):
        return verdict_default(side, code)


