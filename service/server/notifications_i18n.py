def triggers_text(triggers, lang: str = 'en') -> str:
    """Render the hot-issue trigger list in `lang`.

    Unknown triggers pass through verbatim — a new detector must show up in
    the alert as its raw code rather than vanish from it."""
    code = normalize_lang(lang)
    fam = _TRIGGER.get(code, _TRIGGER['en'])
    out = []
    for t in triggers or []:
        t = str(t)
        if t.startswith('price_move:'):
            out.append(fam.get('price_move', '{v}').format(v=t.split(':', 1)[1]))
        else:
            out.append(fam.get(t) or _TRIGGER['en'].get(t, t))
    return ', '.join(out)
