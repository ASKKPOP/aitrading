def _localize_params(lang: str, params: dict) -> dict:
    """Substitute localized text for closed-enum token params, then offer the
    sentence-shaped params to the error catalogue; pass anything else through."""
    out = dict(params)
    resolved: set[str] = set()
    for name in TOKEN_PARAMS:
        if name in out:
            fam = TOKENS.get(name, {})
            key = out[name]
            phrase = fam.get(lang, {}).get(key)
            if phrase is None:
                phrase = fam.get('en', {}).get(key)
            if phrase is None:
                phrase = key          # unknown enum value — may be a sentence
            else:
                resolved.add(name)    # a real token; do not re-translate it
            out[name] = phrase
    if lang != 'en':
        # Imported lazily: i18n_errors pulls in the 300-key error catalogue,
        # and alert rendering must not pay that at module import.
        from i18n_errors import translate
        for name in FREEFORM_PARAMS:
            if name in out and name not in resolved and out[name] is not None:
                out[name] = translate(str(out[name]), lang)
    return out


def _fmt(template: str, params: dict) -> str:
    return template.format(**params)


def render(msg_id: str, lang: str, **params) -> tuple[str, str]:
    """(title, body) for msg_id in lang. Falls back to English on any miss; never raises."""
    variants = MESSAGES.get(msg_id)
    if not variants:
        logger.warning('notifications_i18n: unknown msg_id %r', msg_id)
        return msg_id, ', '.join(f'{k}={v}' for k, v in params.items())
    code = normalize_lang(lang)
    en_title, en_body = variants['en']
    title_t, body_t = variants.get(code, variants['en'])
    lp = _localize_params(code, params)
    try:
        return _fmt(title_t, lp), _fmt(body_t, lp)
    except (KeyError, IndexError, ValueError):
        try:
            en_lp = _localize_params('en', params)
            return _fmt(en_title, en_lp), _fmt(en_body, en_lp)
        except (KeyError, IndexError, ValueError):
            logger.warning('notifications_i18n: param mismatch for %s', msg_id)
            return en_title, en_body


