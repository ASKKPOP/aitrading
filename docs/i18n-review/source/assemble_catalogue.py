"""Assemble the 5-language notification + email catalogues from the translation
intermediates in .superpowers/sdd/. Emits two committable Python modules:

  service/server/notifications_i18n.py   (MESSAGES + TOKENS + render)
  service/server/email_i18n.py           (verification email, 5 langs)

Run from the worktree root. Fails loudly on any placeholder-parity mismatch so
a broken translation can never ship (English fallback still exists at runtime,
but we want the build to catch it).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # worktree root
SD = ROOT / ".superpowers" / "sdd"
LANGS = ["en", "ko", "ja", "th", "vi"]
TOKEN_PARAMS = ["comparator", "outcome", "trigger_label",
                "action", "action_upper", "side", "final", "status"]

PH = re.compile(r"{(\w+)}")


def phset(s: str) -> set[str]:
    return set(PH.findall(s))


def load() -> dict[str, dict]:
    data = {}
    for lang in LANGS:
        fn = SD / (f"translation-source.json" if lang == "en" else f"translation-{lang}.json")
        data[lang] = json.loads(fn.read_text(encoding="utf-8"))
    return data


def validate(data: dict[str, dict]) -> list[str]:
    errs: list[str] = []
    en = data["en"]
    # message placeholder parity
    for mid, mv in en["messages"].items():
        want = phset(mv["title"]) | phset(mv["body"])
        for lang in LANGS:
            m = data[lang]["messages"].get(mid)
            if m is None:
                errs.append(f"{lang}: missing message {mid}")
                continue
            got = phset(m["title"]) | phset(m["body"])
            if got != want:
                errs.append(f"{lang}/{mid}: placeholder mismatch want={sorted(want)} got={sorted(got)}")
    # token family/key parity
    for fam, keys in en["tokens"].items():
        for lang in LANGS:
            t = data[lang]["tokens"].get(fam)
            if t is None:
                errs.append(f"{lang}: missing token family {fam}")
                continue
            if set(t.keys()) != set(keys.keys()):
                errs.append(f"{lang}/{fam}: token keys mismatch")
    # email: html must keep tags + {code}
    for lang in LANGS:
        html = data[lang]["email"]["verification"]["html"]
        if "{code}" not in html or "<strong>" not in html or "<p>" not in html:
            errs.append(f"{lang}: email html missing tag/{{code}}")
        if not data[lang]["email"]["verification"]["subject"].strip():
            errs.append(f"{lang}: empty email subject")
    return errs


def py(s: str) -> str:
    return repr(s)


def emit_notifications(data: dict[str, dict]) -> str:
    en = data["en"]
    mids = list(en["messages"].keys())
    lines = []
    lines.append('"""Localized system-alert copy — 5 languages (en/ko/ja/th/vi).')
    lines.append("")
    lines.append("Producers pass a msg_id + params; send_alert / notify_i18n render (title, body)")
    lines.append("in the recipient's language at send time. English is authoritative and complete;")
    lines.append("ko/ja/th/vi are machine-generated and pending native review (a wrong or missing")
    lines.append("(lang, msg_id) or any param mismatch renders in English — never raises).")
    lines.append("")
    lines.append("TOKENS localizes the few closed enum phrases that appear inside sentences")
    lines.append("(comparator/outcome/trigger_label). Free-form runtime strings (an engine-returned")
    lines.append("reason, an exception message) are passed through as-is — they cannot be")
    lines.append("pre-translated without a live MT service.")
    lines.append("")
    lines.append("This module is generated by .superpowers/sdd/assemble_catalogue.py from the")
    lines.append("translation intermediates, then committed as a normal editable module.")
    lines.append('"""')
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("import logging")
    lines.append("")
    lines.append("from analysis_agents import normalize_lang")
    lines.append("")
    lines.append("logger = logging.getLogger(__name__)")
    lines.append("")
    lines.append("# Param names whose values are closed enum keys localized via TOKENS below.")
    lines.append(f"TOKEN_PARAMS = {TOKEN_PARAMS!r}")
    lines.append("")
    lines.append("# family -> lang -> key -> localized phrase")
    lines.append("TOKENS: dict[str, dict[str, dict[str, str]]] = {")
    for fam in en["tokens"]:
        lines.append(f"    {fam!r}: {{")
        for lang in LANGS:
            lines.append(f"        {lang!r}: {{")
            for k in en["tokens"][fam]:
                v = data[lang]["tokens"][fam][k]
                lines.append(f"            {k!r}: {py(v)},")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    lines.append("# msg_id -> lang -> (title_template, body_template)")
    lines.append("MESSAGES: dict[str, dict[str, tuple[str, str]]] = {")
    for mid in mids:
        lines.append(f"    {mid!r}: {{")
        for lang in LANGS:
            m = data[lang]["messages"][mid]
            lines.append(f"        {lang!r}: ({py(m['title'])}, {py(m['body'])}),")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    lines.append("")
    lines.append("def _localize_params(lang: str, params: dict) -> dict:")
    lines.append('    """Substitute localized text for closed-enum token params; pass others through."""')
    lines.append("    out = dict(params)")
    lines.append("    for name in TOKEN_PARAMS:")
    lines.append("        if name in out:")
    lines.append("            fam = TOKENS.get(name, {})")
    lines.append("            key = out[name]")
    lines.append("            phrase = fam.get(lang, {}).get(key)")
    lines.append("            if phrase is None:")
    lines.append("                phrase = fam.get('en', {}).get(key, key)")
    lines.append("            out[name] = phrase")
    lines.append("    return out")
    lines.append("")
    lines.append("")
    lines.append("def _fmt(template: str, params: dict) -> str:")
    lines.append("    return template.format(**params)")
    lines.append("")
    lines.append("")
    lines.append("def render(msg_id: str, lang: str, **params) -> tuple[str, str]:")
    lines.append('    """(title, body) for msg_id in lang. Falls back to English on any miss; never raises."""')
    lines.append("    variants = MESSAGES.get(msg_id)")
    lines.append("    if not variants:")
    lines.append("        logger.warning('notifications_i18n: unknown msg_id %r', msg_id)")
    lines.append("        return msg_id, ', '.join(f'{k}={v}' for k, v in params.items())")
    lines.append("    code = normalize_lang(lang)")
    lines.append("    en_title, en_body = variants['en']")
    lines.append("    title_t, body_t = variants.get(code, variants['en'])")
    lines.append("    lp = _localize_params(code, params)")
    lines.append("    try:")
    lines.append("        return _fmt(title_t, lp), _fmt(body_t, lp)")
    lines.append("    except (KeyError, IndexError, ValueError):")
    lines.append("        try:")
    lines.append("            en_lp = _localize_params('en', params)")
    lines.append("            return _fmt(en_title, en_lp), _fmt(en_body, en_lp)")
    lines.append("        except (KeyError, IndexError, ValueError):")
    lines.append("            logger.warning('notifications_i18n: param mismatch for %s', msg_id)")
    lines.append("            return en_title, en_body")
    lines.append("")
    return "\n".join(lines)


def emit_email(data: dict[str, dict]) -> str:
    lines = []
    lines.append('"""Localized transactional email copy (verification / reset code), 5 languages.')
    lines.append("")
    lines.append("English is authoritative; ko/ja/th/vi are machine-generated pending native review.")
    lines.append("Unknown language falls back to English via normalize_lang + .get.")
    lines.append("")
    lines.append("Generated by .superpowers/sdd/assemble_catalogue.py, committed as an editable module.")
    lines.append('"""')
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("from analysis_agents import normalize_lang")
    lines.append("")
    lines.append("# {lang: (subject, html_template)}; html_template has a single {code} slot.")
    lines.append("_VERIFICATION = {")
    for lang in LANGS:
        v = data[lang]["email"]["verification"]
        lines.append(f"    {lang!r}: ({py(v['subject'])},")
        lines.append(f"           {py(v['html'])}),")
    lines.append("}")
    lines.append("")
    lines.append("")
    lines.append("def verification_email(code: str, lang: str) -> tuple[str, str]:")
    lines.append("    subject, template = _VERIFICATION.get(normalize_lang(lang), _VERIFICATION['en'])")
    lines.append("    return subject, template.format(code=code)")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    data = load()
    errs = validate(data)
    if errs:
        print("VALIDATION FAILED:")
        for e in errs:
            print("  -", e)
        return 1
    (ROOT / "service/server/notifications_i18n.py").write_text(emit_notifications(data), encoding="utf-8")
    (ROOT / "service/server/email_i18n.py").write_text(emit_email(data), encoding="utf-8")
    print("OK: wrote notifications_i18n.py + email_i18n.py")
    print(f"messages={len(data['en']['messages'])} langs={LANGS} token_families={list(data['en']['tokens'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
